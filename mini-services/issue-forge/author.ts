/* ═══ issue-forge · author.ts — Mode A (real characterization) · Mode B (LLM diff) ══
 * Mode A (deterministic, testgap issues): probes the audited module in a bounded
 *   child process, captures REAL outputs of ≥3 deterministic calls (double-run
 *   determinism proof), and generates tests/<name>.forge.test.ts asserting the
 *   captured values — a genuine TDD characterization suite, never invented.
 * Mode B (todo issues): asks the LLM for a unified diff (direct z-ai-web-dev-sdk
 *   import; fallback: the local edge API POST /api/sovereign/channel/ask — its
 *   request/response contract is {text, token} → {ok, answer}|{ok:false, error}).
 *   The patch must pass `git apply --check`, touch ONLY the target file, and if
 *   it fails twice the loop records author-refused honestly. No fabricated diffs.
 */
import fs from "node:fs";
import path from "node:path";

import { SERVICE_DIR, sh } from "./forge.ts";

/* ── Mode A: probe ────────────────────────────────────────────────────────── */
export interface ProbeCase {
  args: unknown[];
  out: string;
  isAsync: boolean;
}

export interface ProbeResult {
  ok: boolean;
  name?: string;
  cases?: ProbeCase[];
  async?: boolean;
  reason?: string;
}

const PROBE_TIMEOUT_MS = 25_000;

async function probeOnce(repoRoot: string, relModule: string, prefer?: string): Promise<ProbeResult> {
  const runner = path.join(SERVICE_DIR, "probe-runner.ts");
  const abs = path.join(repoRoot, relModule);
  try {
    const proc = Bun.spawn(["bun", runner, abs, prefer ?? ""], {
      cwd: repoRoot,
      stdout: "pipe",
      stderr: "pipe",
      timeout: PROBE_TIMEOUT_MS,
    });
    const stdout = await new Response(proc.stdout).text();
    await proc.exited;
    /* the module under probe may print on import — scan from the END for the
       last line that parses as a probe result object */
    for (const line of stdout.trim().split("\n").reverse()) {
      try {
        const j = JSON.parse(line) as ProbeResult;
        if (typeof j.ok === "boolean") return j;
      } catch {
        /* not the result line — keep scanning */
      }
    }
    return { ok: false, reason: "probe-no-result-line" };
  } catch (e) {
    return { ok: false, reason: "probe-spawn-failed: " + (e instanceof Error ? e.message : String(e)) };
  }
}

export async function probeFunction(
  repoRoot: string,
  relModule: string,
  prefer?: string,
): Promise<ProbeResult> {
  /* מחזור 31 · הוכחת-דטרמיניזם חוצת-תהליכים: שני-תהליכי-probe טריים-ונפרדים
   * חייבים-ללכוד cases זהים-במדויק. הרצה-כפולה-בתוך-תהליך-אחד מאשרת-מצב-מקומי
   * לתהליך (זמן-אתחול-מודול, seeds, מונים) שעובר-ב-probe ונופל-ב-gate. אי-התאמה
   * = סירוב-כן — אף-מבחן-שברירי לא-נוצר-מעולם. */
  const a = await probeOnce(repoRoot, relModule, prefer);
  if (!a.ok) return a;
  const b = await probeOnce(repoRoot, relModule, prefer);
  if (!b.ok) return b;
  const key = (r: ProbeResult) => JSON.stringify({ name: r.name, cases: r.cases });
  if (key(a) !== key(b)) {
    return { ok: false, reason: `cross-process-nondeterministic:${a.name ?? "?"}` };
  }
  return a;
}

export function buildModeATest(input: {
  relModule: string;
  fnName: string;
  cases: ProbeCase[];
  isAsync: boolean;
  issue: number;
  cycle: number;
}): string {
  const importPath = "../" + input.relModule.replace(/\.(ts|tsx)$/, "");
  const head = `/**
 * ${path.basename(importPath)}.forge.test.ts — characterization suite generated by
 * issue-forge (Mode A · issue #${input.issue} · cycle ${input.cycle}).
 * Every assertion was CAPTURED from real execution of the current implementation
 * at authoring time (probe-runner; determinism proved by a double run) — never
 * invented. If a future change alters a captured output this suite goes RED and
 * forces a conscious review of the behavioral change.
 * Generated file: do not hand-edit captured values; regenerate instead.
 */
import { describe, expect, test } from "bun:test";
import * as mod from ${JSON.stringify(importPath)};

function canon(v: unknown): string {
  if (v === null || typeof v !== "object") return JSON.stringify(v) ?? "undefined";
  if (Array.isArray(v)) return "[" + v.map(canon).join(",") + "]";
  const o = v as Record<string, unknown>;
  return "{" + Object.keys(o).sort().map((k) => JSON.stringify(k) + ":" + canon(o[k])).join(",") + "}";
}
`;
  const body = input.cases
    .map((c, i) => {
      const argsLit = JSON.stringify(c.args);
      const title = JSON.stringify(`case ${i + 1}: captured output of ${input.fnName}(${argsLit})`);
      const awaitKw = input.isAsync ? "await " : "";
      const asyncKw = input.isAsync ? "async " : "";
      return [
        `  test(${title}, ${asyncKw}() => {`,
        `    const actual = ${awaitKw}fn(...${argsLit} as unknown[]);`,
        `    expect(canon(actual)).toBe(${JSON.stringify(c.out)});`,
        `  });`,
      ].join("\n");
    })
    .join("\n");
  return `${head}
describe("${input.relModule}.${input.fnName} (forge characterization #${input.issue})", () => {
  const fn = (mod as Record<string, unknown>)["${input.fnName}"] as (...a: unknown[]) => unknown;
${body}
});
`;
}

/* ── Mode B: LLM diff ─────────────────────────────────────────────────────── */
export const FORGE_SYSTEM_PROMPT = [
  "You are the sovereign-forge authoring engine of the giant repository (§9 loop).",
  "OUTPUT CONTRACT: exactly one unified diff (git-apply compatible). No prose, no markdown fences.",
  "LAWS: no new TODO/FIXME/XXX/STUB markers; never delete a marker without implementing the real behavior behind it;",
  "no mocks, stubs or placeholder code; TypeScript must compile; modify ONLY the target file given in the prompt;",
  "respect existing code style. If the change is not safely automatable, output exactly: REFUSE",
].join(" ");

export function buildModeBPrompt(input: {
  issueTitle: string;
  issueBody: string;
  target: string;
  fileContent: string;
}): string {
  return [
    `ISSUE: ${input.issueTitle}`,
    input.issueBody,
    "",
    `TARGET FILE (current content, path ${input.target}):`,
    "```",
    input.fileContent,
    "```",
    "",
    "TASK: produce the minimal correct patch implementing the acceptance criteria above.",
    "OUTPUT CONTRACT: a single unified diff for the target file only. No prose, no markdown fences.",
    "If not safely automatable, output exactly: REFUSE",
  ].join("\n");
}

export function extractDiff(text: string): string | null {
  const cleaned = text.replace(/```[a-zA-Z]*\n?/g, "").trim();
  const idx = cleaned.indexOf("diff --git");
  if (idx >= 0) {
    const diff = cleaned.slice(idx).trim();
    return diff.length > 20 ? diff : null;
  }
  const m = /^---\s+a\/\S+.*$/m.exec(cleaned);
  if (m && m.index !== undefined) {
    const diff = cleaned.slice(m.index).trim();
    return diff.length > 20 ? diff : null;
  }
  return null;
}

export interface PatchStage {
  file: string;
  cleanup(): void;
}

/** writes the diff under .git/ (never seen by status, never committed) */
export function stagePatch(repoRoot: string, diff: string): PatchStage {
  const file = path.join(repoRoot, ".git", `forge-patch-${process.pid}-${Date.now()}.patch`);
  fs.writeFileSync(file, diff.endsWith("\n") ? diff : diff + "\n");
  return { file, cleanup: () => { try { fs.unlinkSync(file); } catch { /* honest */ } } };
}

/** scope law + git apply --check. Returns {ok} or an honest reason. */
export async function validatePatch(
  repoRoot: string,
  diff: string,
  allowedTarget: string,
): Promise<{ ok: boolean; reason?: string }> {
  const touched = new Set<string>();
  for (const m of diff.matchAll(/^[-+]{3}\s+[ab]\/(.+)$/gm)) {
    const p = m[1].replace(/[\t ].*$/, "");
    if (p !== "/dev/null") touched.add(p);
  }
  if (touched.size === 0) return { ok: false, reason: "empty-diff" };
  for (const p of touched) {
    if (p !== allowedTarget) return { ok: false, reason: `scope-violation: ${p}` };
  }
  const stage = stagePatch(repoRoot, diff);
  try {
    const r = await sh("git", ["apply", "--check", "--whitespace=nowarn", path.relative(repoRoot, stage.file)], repoRoot, 30_000);
    return r.code === 0 ? { ok: true } : { ok: false, reason: "apply-check-failed: " + r.out.slice(-300) };
  } finally {
    stage.cleanup();
  }
}

/* ── LLM transports (SDK direct → edge ask route fallback) ────────────────── */
const LLM_TIMEOUT_MS = 90_000;
const EDGE_ASK_URL = "http://127.0.0.1:3000/api/sovereign/channel/ask";
const EDGE_TEXT_CAP = 1900; // the ask route rejects text > 2000 chars

interface SdkCompletionShape {
  choices?: { message?: { content?: string } }[];
}

async function sdkChat(system: string, user: string): Promise<string | null> {
  try {
    const mod = (await import("z-ai-web-dev-sdk")) as {
      default?: { create(): Promise<{ chat: { completions: { create(x: unknown): Promise<SdkCompletionShape> } } }> };
    };
    const ZAI = mod.default;
    if (!ZAI) return null;
    const zai = await ZAI.create();
    const completion = await Promise.race([
      zai.chat.completions.create({
        messages: [
          { role: "assistant", content: system },
          { role: "user", content: user },
        ],
        thinking: { type: "disabled" },
      }),
      new Promise<never>((_, rej) => setTimeout(() => rej(new Error("LLM_TIMEOUT")), LLM_TIMEOUT_MS)),
    ]);
    return completion?.choices?.[0]?.message?.content?.trim() ?? null;
  } catch {
    return null;
  }
}

async function edgeAsk(prompt: string): Promise<string | null> {
  /* matches POST /api/sovereign/channel/ask: {text (≤2000), token} → {ok, answer} | {ok:false,error} */
  try {
    const res = await fetch(EDGE_ASK_URL, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        text: prompt.length > EDGE_TEXT_CAP ? prompt.slice(0, EDGE_TEXT_CAP) : prompt,
        token: process.env.SOVEREIGN_GATE_TOKEN ?? "",
      }),
      signal: AbortSignal.timeout(60_000),
    });
    const j = (await res.json().catch(() => null)) as { ok?: boolean; answer?: string } | null;
    if (res.ok && j?.ok && typeof j.answer === "string") return j.answer;
    return null;
  } catch {
    return null;
  }
}

export interface LlmDiffResult {
  diff: string | null;
  via: "sdk" | "edge" | "none";
  refused: boolean;
}

export async function llmDiff(system: string, prompt: string): Promise<LlmDiffResult> {
  const a = await sdkChat(system, prompt);
  if (a) {
    if (a.trim() === "REFUSE") return { diff: null, via: "sdk", refused: true };
    const d = extractDiff(a);
    if (d) return { diff: d, via: "sdk", refused: false };
  }
  const b = await edgeAsk(prompt);
  if (b) {
    if (b.trim() === "REFUSE") return { diff: null, via: "edge", refused: true };
    const d = extractDiff(b);
    if (d) return { diff: d, via: "edge", refused: false };
  }
  return { diff: null, via: a || b ? "sdk" : "none", refused: false };
}
